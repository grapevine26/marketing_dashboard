import type { SeedingRecord } from "@/lib/db/types";

/**
 * 이 인플루언서가 **업로드를 끝냈는가**.
 *
 * 판정이 세 곳에 따로 적혀 있다가 한 곳만 기준이 달랐다. 결과보고서와 캠페인 상세는
 * "단계가 업로드완료이거나 **업로드 링크가 붙어 있으면**" 끝난 것으로 셌는데,
 * 홈 오버뷰는 단계만 봤다. 그래서 인플루언서가 링크를 붙여 넣었지만 담당자가 아직
 * 단계를 안 옮긴 흔한 상태에서, **같은 사람을 두고 한 화면은 "완료", 다른 화면은
 * "업로드 마감 임박"** 이라고 말했다. 숫자가 어긋나는 정도가 아니라 서로 반대였다.
 *
 * 링크를 포함하는 쪽이 맞다. 링크가 붙었다는 것은 인플루언서가 할 일을 했다는 뜻이고,
 * 단계는 담당자가 나중에 정리하는 값이라 늦게 따라온다. 재촉 알림의 기준으로는
 * "사람이 아직 안 올렸는가" 가 맞지 "담당자가 아직 정리 안 했는가" 가 아니다.
 */
export function isUploadDone(s: Pick<SeedingRecord, "progress_stage" | "upload_link">): boolean {
  return s.progress_stage === "업로드완료" || Boolean(s.upload_link);
}
