import { describe, it, expect } from "vitest";
import { generateCSV } from "@/lib/export/csv";

/**
 * CSV 한 칸이 엑셀에서 **수식으로 실행되지 않게** 하면서, 동시에 **읽을 수 있는 파일**이어야 한다.
 *
 * 두 요구가 부딪힌다. 지원자가 이름 칸에 `=HYPERLINK("http://…")` 를 적어 넣으면 그 파일을 여는
 * 광고주의 엑셀에서 실행되므로 막아야 한다. 그런데 막는 규칙을 `- + = @ 로 시작하면 전부` 로 두면
 * 이 앱이 **빈 칸을 표시하는 `-`** 와 해외 연락처 `+82 10-…` 까지 걸려서, 광고주가 받는 파일이
 * `'-` 로 도배된다.
 *
 * 그래서 "수식이 될 수 없는 모양"(글자 하나짜리 대시, 부호로 시작하는 평범한 숫자)만 빼 준다.
 */
const 한칸 = (v: string | number) => generateCSV(["h"], [[v]]).split("\n")[1];

describe("CSV 수식 주입 방어", () => {
  it("수식이 될 수 있는 값은 작은따옴표로 무력화한다", () => {
    // 지원자가 공개 신청폼으로 넣을 수 있는 값들이다. 로그인 없이 들어온다.
    for (const 값 of [
      '=HYPERLINK("http://evil.example/","click")',
      "=1+1",
      "+1+cmd|' /C calc'!A0",
      "-1+1+cmd|' /C calc'!A0",
      "@SUM(1+1)",
      "\t=1+1",
      "\r=1+1",
    ]) {
      expect(한칸(값), `무력화되지 않았다: ${JSON.stringify(값)}`).toBe(`"'${값.replace(/"/g, '""')}"`);
    }
  });

  it("수식이 될 수 없는 모양은 그대로 둔다", () => {
    // 이것들이 `'` 로 더럽혀지면 광고주가 받는 표가 통째로 읽기 나빠진다.
    expect(한칸("-")).toBe('"-"'); // 빈 값 표시. 관리시트 대부분의 칸이 이 모양이다.
    expect(한칸("+82 10-1234-5678")).toBe('"+82 10-1234-5678"');
    expect(한칸("010-1234-5678")).toBe('"010-1234-5678"');
    expect(한칸("-1,234")).toBe('"-1,234"');
    expect(한칸("-0.5")).toBe('"-0.5"');
    expect(한칸(-42)).toBe('"-42"');
    expect(한칸("김서연")).toBe('"김서연"');
    expect(한칸("")).toBe('""');
  });

  it("따옴표·쉼표·줄바꿈이 든 값도 칸을 깨지 않는다", () => {
    expect(한칸('그가 "그렇다" 고 했다')).toBe('"그가 ""그렇다"" 고 했다"');
    // 쉼표와 줄바꿈은 따옴표로 감싸는 것으로 충분하다(RFC 4180).
    expect(한칸("가, 나")).toBe('"가, 나"');
    expect(generateCSV(["h"], [["첫 줄\n둘째 줄"]])).toContain('"첫 줄\n둘째 줄"');
  });

  it("헤더도 같은 규칙을 받는다", () => {
    // 커스텀 질문 문구가 그대로 헤더가 된다. 직원이 적는 값이지만 예외를 둘 이유가 없다.
    // 엑셀이 한글을 깨뜨리지 않게 BOM 을 붙이고 줄끝은 CRLF 다. 헤더만 떼어 본다.
    const 헤더 = generateCSV(["=1+1"], []).split("\n")[0]!.replace(/^﻿/, "").replace(/\r$/, "");
    expect(헤더).toBe("\"'=1+1\"");
  });
});
